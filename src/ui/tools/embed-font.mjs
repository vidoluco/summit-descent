// Regenerates src/ui/font-data.js from src/ui/fonts/fredoka-latin.woff2, so the host page carries its font
// inside dist/game.js and needs no network at runtime. Usage: node src/ui/tools/embed-font.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const woff2 = readFileSync('src/ui/fonts/fredoka-latin.woff2');
writeFileSync('src/ui/font-data.js', `// Generated by src/ui/tools/embed-font.mjs from src/ui/fonts/fredoka-latin.woff2. Do not edit.
// Fredoka (latin subset, weights 500 to 700), SIL Open Font License 1.1, see src/ui/fonts/OFL.txt.
export const FREDOKA_WOFF2 = '${woff2.toString('base64')}';
`);
console.log(`src/ui/font-data.js: ${woff2.length} bytes of woff2`);
